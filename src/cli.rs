use clap::{Arg, ArgAction};

pub fn git_mob_cmd() -> clap::Command {
    clap::Command::new("git-mob")
        .bin_name("git-mob")
        .author("Martin Frost, martin@frost.codes")
        .version("0.0.0")
        .about("A command-line tool for social coding")
        .arg(Arg::new("add")
             .display_order(3)
             .exclusive(true)
             .help("Add a coauthor to the database")
             .long("add-coauthor")
             .num_args(3)
             .short('a')
             .value_names(["handle", "name", "email"])
        )
        .arg(Arg::new("edit")
             .display_order(3)
             .exclusive(true)
             .help("Edit a coauthor in the database")
             .long("edit-coauthor")
             .num_args(3)
             .short('e')
             .value_names(["handle", "name", "email"])
        )
        .arg(Arg::new("delete")
             .display_order(3)
             .exclusive(true)
             .help("Delete a coauthor from the database")
             .long("delete-coauthor")
             .short('d')
             .value_name("handle")
        )
        .arg(Arg::new("solo")
             .action(ArgAction::SetTrue)
             .display_order(1)
             .exclusive(true)
             .help("Continue on your coding quest by yourself")
             .long("solo")
             .short('s')
        )
        .arg(Arg::new("list")
             .action(ArgAction::SetTrue)
             .display_order(4)
             .exclusive(true)
             .help("List available coauthors in the database")
             .long("list-coauthors")
             .short('l')
        )
        .arg(Arg::new("with")
             .conflicts_with_all(["add", "edit", "delete", "solo", "list"])
             .exclusive(true)
             .help("Choose coauthors to help you on your coding quest")
             .long("with")
             .num_args(1..)
             .short('w')
             .display_order(0)
             .value_name("handle")
        )
        .arg(Arg::new("current")
             .action(ArgAction::SetTrue)
             .display_order(2)
             .exclusive(true)
             .help("Show current mob (including main author)")
             .long("current-mob")
             .short('c')
        )
}
